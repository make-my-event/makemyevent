ALTER TABLE "events"
  ADD CONSTRAINT "events_slug_format"
    CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) <= 80),
  -- An event's dashboard is /dashboard/{slug}, beside the lists at
  -- /dashboard/organized and /dashboard/attending. Those pages would always
  -- win, so an event may not take their names. Add any new /dashboard/{word}
  -- page here, in the same change.
  ADD CONSTRAINT "events_slug_not_reserved"
    CHECK (slug NOT IN ('organized', 'attending')),
  ADD CONSTRAINT "events_title_length"
    CHECK (length(btrim(title)) BETWEEN 1 AND 120),
  ADD CONSTRAINT "events_description_length"
    CHECK (length(description) <= 20000),
  ADD CONSTRAINT "events_format"
    CHECK (format IN ('offline', 'online', 'hybrid')),
  ADD CONSTRAINT "events_venue_length"
    CHECK (length(venue_name) <= 200 AND length(venue_address) <= 500),
  ADD CONSTRAINT "events_time_zone_length"
    CHECK (length(time_zone) BETWEEN 1 AND 64),
  ADD CONSTRAINT "events_ends_after_start"
    CHECK (ends_at > starts_at),
  ADD CONSTRAINT "events_registration_window"
    CHECK (registration_closes_at > registration_opens_at),
  ADD CONSTRAINT "events_registration_closes_by_end"
    CHECK (registration_closes_at <= ends_at),
  ADD CONSTRAINT "events_capacity_positive"
    CHECK (capacity > 0),
  ADD CONSTRAINT "events_currency_format"
    CHECK (currency ~ '^[A-Z]{3}$'),
  ADD CONSTRAINT "events_image_path_length"
    CHECK (length(logo_path) <= 512 AND length(poster_path) <= 512),
  ADD CONSTRAINT "events_status"
    CHECK (status IN ('draft', 'published', 'cancelled')),
  -- Only a published event can be cancelled; drafts are deleted instead.
  -- So anything not a draft has been public, and has what a page needs.
