-- ---------------------------------------------------------------------------
-- Who may do what
--
-- The host manages everything about their event. Anyone, signed in or not,
-- can read an event that has been published, with its links, days and
-- tickets, since its public page shows them. Invites are the host's alone.
-- Organizations and co-hosts will widen app.manages_event, and every policy
-- below follows.
-- ---------------------------------------------------------------------------

CREATE FUNCTION app.manages_event(target uuid) RETURNS boolean
  LANGUAGE sql STABLE
  AS $$
    SELECT EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = target AND e.host_user_id = app.current_user_id()
    )
  $$;

CREATE FUNCTION app.can_see_event(target uuid) RETURNS boolean
  LANGUAGE sql STABLE
  AS $$
    SELECT EXISTS (
      SELECT 1 FROM public.events e
      WHERE e.id = target
        AND (e.status <> 'draft' OR e.host_user_id = app.current_user_id())
    )
  $$;

GRANT EXECUTE ON FUNCTION app.manages_event(uuid), app.can_see_event(uuid)
  TO app_user;

