DECLARE
  t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['event_links', 'event_days', 'ticket_types',
                           'ticket_type_days'] LOOP
    EXECUTE format(
      'CREATE POLICY %1$s_select ON %1$I FOR SELECT TO app_user
         USING (app.can_see_event(event_id))', t);
    EXECUTE format(
      'CREATE POLICY %1$s_insert ON %1$I FOR INSERT TO app_user
         WITH CHECK (app.manages_event(event_id))', t);
    EXECUTE format(
      'CREATE POLICY %1$s_update ON %1$I FOR UPDATE TO app_user
         USING (app.manages_event(event_id))
         WITH CHECK (app.manages_event(event_id))', t);
    EXECUTE format(
      'CREATE POLICY %1$s_delete ON %1$I FOR DELETE TO app_user
         USING (app.manages_event(event_id))', t);
  END LOOP;
END
$$;

