    CHECK (
      status = 'draft' OR (
        published_at IS NOT NULL
        AND time_zone IS NOT NULL
        AND starts_at IS NOT NULL
        AND ends_at IS NOT NULL
        AND currency IS NOT NULL
        AND (format = 'online' OR venue_name IS NOT NULL)
      )
    );

