CREATE POLICY events_select ON "events"
  FOR SELECT TO app_user
  USING (status <> 'draft' OR host_user_id = app.current_user_id());

CREATE POLICY events_insert ON "events"
  FOR INSERT TO app_user
  WITH CHECK (host_user_id = app.current_user_id());

CREATE POLICY events_update ON "events"
  FOR UPDATE TO app_user
  USING (host_user_id = app.current_user_id())
  WITH CHECK (host_user_id = app.current_user_id());

-- A published event is cancelled, never deleted: people hold its tickets.
CREATE POLICY events_delete ON "events"
  FOR DELETE TO app_user
  USING (host_user_id = app.current_user_id() AND status = 'draft');

